package laravelcrypt_test

import (
	"fmt"

	laravelcrypt "github.com/Rene-Roscher/laravel-go-encryption"
)

// A fixed key in Laravel's APP_KEY "base64:" form (32 raw bytes).
const exampleKey = "base64:KysrKysrKysrKysrKysrKysrKysrKysrKysrKysrKys="

// Encrypt a value in Go and decrypt it back (the value is also decryptable by Laravel's
// Crypt::decryptString with the same key).
func Example() {
	enc, err := laravelcrypt.New(exampleKey, "aes-256-cbc")
	if err != nil {
		panic(err)
	}

	payload, err := enc.EncryptString("hello from go")
	if err != nil {
		panic(err)
	}

	plain, err := enc.DecryptString(payload)
	if err != nil {
		panic(err)
	}
	fmt.Println(plain)
	// Output: hello from go
}

